def build_chunk_pattern(chunk: str) -> re.Pattern:
    """
    Build a case-insensitive regex pattern matching a phrasal verb/expression
    even when its leading verb is inflected (e.g., 'put off' -> 'putting off', 'make sense' -> 'makes sense').
    """
    words = chunk.split()
    first = words[0].lower()
    if first in VERB_INFLECTIONS:
        first_pat = "(?:" + "|".join(re.escape(form) for form in VERB_INFLECTIONS[first]) + ")"
    else:
        first_pat = re.escape(words[0])

    parts = [first_pat] + [re.escape(w) for w in words[1:]]
    return re.compile(r"\b" + r"\s+".join(parts) + r"\b", re.IGNORECASE)


def lemmatize_word(word: str) -> str:
    """
    Normalize common English inflections/plurals to a base key in CORE_DICTIONARY when available.
    """
    w = re.sub(r"[^a-zA-Z]", "", (word or "").strip().lower())
    if not w:
        return ""
    if w in CORE_DICTIONARY:
        return w
    if w in IRREGULAR_LEMMAS:
        mapped = IRREGULAR_LEMMAS[w]
        return mapped if mapped in CORE_DICTIONARY else w

    candidates: List[str] = []
    if w.endswith("ies") and len(w) > 4:
        candidates.append(w[:-3] + "y")
    if w.endswith("ied") and len(w) > 4:
        candidates.append(w[:-3] + "y")
    if w.endswith("es") and len(w) > 4:
        candidates.append(w[:-2])
    if w.endswith("s") and len(w) > 3:
        candidates.append(w[:-1])
    if w.endswith("ing") and len(w) > 4:
        stem = w[:-3]
        candidates.extend([stem, stem + "e"])
        if len(stem) >= 3 and stem[-1] == stem[-2]:
            candidates.append(stem[:-1])
    if w.endswith("ed") and len(w) > 4:
        stem = w[:-2]
        candidates.extend([stem, stem + "e"])
        if len(stem) >= 3 and stem[-1] == stem[-2]:
            candidates.append(stem[:-1])
    if w.endswith("d") and len(w) > 3:
        candidates.append(w[:-1])

    for cand in candidates:
        if cand in CORE_DICTIONARY:
            return cand

    return w


def lookup_local_translation(term: str) -> Optional[str]:
    """
    Look up an idiomatic PT-BR translation from PHRASAL_VERBS_AND_CHUNKS or CORE_DICTIONARY.
    Never extracts a single-word translation for multi-word expressions.
    """
    clean_lower = (term or "").strip().lower()
    if not clean_lower:
        return None

    if clean_lower in PHRASAL_VERBS_AND_CHUNKS:
        return PHRASAL_VERBS_AND_CHUNKS[clean_lower]["translation"]

    # Do not translate multi-word expressions via single-word dictionary lookup
    if " " in clean_lower:
        return None

    clean_single = re.sub(r"[^a-zA-Z]", "", clean_lower)
    if not clean_single:
        return None

    if clean_single in CORE_DICTIONARY:
        return CORE_DICTIONARY[clean_single]["translation"].split(",")[0].strip()

    stem = lemmatize_word(clean_single)
    if stem in CORE_DICTIONARY:
        return CORE_DICTIONARY[stem]["translation"].split(",")[0].strip()

    return None
